const grid = document.querySelector('#story-grid');
const cards = [...document.querySelectorAll('.story-card')];
const filterButtons = [...document.querySelectorAll('.filter-chip')];
const searchInput = document.querySelector('#story-search');
const emptyState = document.querySelector('#empty-state');
let activeFilter = 'All';

function applyFilters() {
  const query = searchInput.value.trim().toLocaleLowerCase();
  let visible = 0;
  cards.forEach(card => {
    const matchesCategory = activeFilter === 'All' || card.dataset.category === activeFilter;
    const matchesQuery = `${card.dataset.title} ${card.dataset.category} ${card.querySelector('.story-summary')?.textContent ?? ''}`.toLocaleLowerCase().includes(query);
    card.hidden = !(matchesCategory && matchesQuery);
    if (!card.hidden) visible++;
  });
  emptyState.hidden = visible !== 0;
  grid.setAttribute('aria-label', `${visible} ${visible === 1 ? 'story' : 'stories'} shown`);
}
filterButtons.forEach(button => button.addEventListener('click', () => {
  activeFilter = button.dataset.filter;
  filterButtons.forEach(item => {
    const selected = item === button;
    item.classList.toggle('active', selected);
    item.setAttribute('aria-pressed', String(selected));
  });
  applyFilters();
}));
searchInput.addEventListener('input', applyFilters);

const dialog = document.querySelector('#story-dialog');
const dialogImage = document.querySelector('#dialog-image');
const dialogCategory = document.querySelector('#dialog-category');
const dialogMeta = document.querySelector('#dialog-meta');
const dialogTitle = document.querySelector('#dialog-title');
const dialogDeck = document.querySelector('#dialog-deck');
const dialogBody = document.querySelector('#dialog-body');
let previousFocus = null;
function openStory(id) {
  const story = stories[id];
  if (!story) return;
  previousFocus = document.activeElement;
  dialogImage.src = story.image;
  dialogImage.alt = story.alt;
  dialogCategory.textContent = story.category;
  dialogMeta.textContent = `${story.label}   /   ${story.minutes}`;
  dialogTitle.textContent = story.title;
  dialogDeck.textContent = story.deck;
  dialogBody.replaceChildren(...story.body.map(paragraph => {
    const p = document.createElement('p');
    p.textContent = paragraph;
    return p;
  }));
  if (typeof dialog.showModal === 'function') dialog.showModal();
  else dialog.setAttribute('open', '');
  document.body.classList.add('dialog-open');
}
function closeStory() {
  if (typeof dialog.close === 'function') dialog.close();
  else dialog.removeAttribute('open');
  document.body.classList.remove('dialog-open');
  previousFocus?.focus();
}
document.querySelectorAll('[data-story]').forEach(button => button.addEventListener('click', () => openStory(button.dataset.story)));
document.querySelector('.dialog-close').addEventListener('click', closeStory);
document.querySelector('.dialog-next').addEventListener('click', closeStory);
dialog.addEventListener('click', event => {
  const rect = dialog.getBoundingClientRect();
  const outside = event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom;
  if (event.target === dialog && outside) closeStory();
});
dialog.addEventListener('close', () => {
  document.body.classList.remove('dialog-open');
  previousFocus?.focus();
});

const menuToggle = document.querySelector('.menu-toggle');
const mobileNav = document.querySelector('#mobile-nav');
menuToggle.addEventListener('click', () => {
  const expanded = menuToggle.getAttribute('aria-expanded') === 'true';
  menuToggle.setAttribute('aria-expanded', String(!expanded));
  menuToggle.setAttribute('aria-label', expanded ? 'Open navigation' : 'Close navigation');
  mobileNav.hidden = expanded;
});
mobileNav.querySelectorAll('a').forEach(link => link.addEventListener('click', () => {
  menuToggle.setAttribute('aria-expanded', 'false');
  menuToggle.setAttribute('aria-label', 'Open navigation');
  mobileNav.hidden = true;
}));
